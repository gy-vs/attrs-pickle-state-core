# The doc prefix attrs puts on every dunder method it generates via
# _add_method_dunders.
_AUTOGEN_DOC_PREFIX = "Method generated by attrs for class "


def _has_autogenerated(cls, name):
    """
    Return True if *cls* itself carries an attrs-generated *name* method.
    """
    meth = cls.__dict__.get(name)
    return (
        callable(meth)
        and meth.__name__ == name
        and (meth.__doc__ or "").startswith(_AUTOGEN_DOC_PREFIX)
    )


def roundtrip(obj, protocol=None):
    return pickle.loads(pickle.dumps(obj, protocol))


