class TestCacheHash(object):
    @pytest.mark.parametrize("protocol", PROTOCOLS)
    def test_slots_cache_hash_not_serialized(self, protocol):
        c = SlotCacheHash(11)
        h = hash(c)
        assert getattr(c, "_attrs_cached_hash") is not None

        assert c.__getstate__() == (11,)

        c2 = roundtrip(c, protocol)
        # Reset, not restored from a stale serialized value.
        assert c2._attrs_cached_hash is None
        assert hash(c2) == h

    @pytest.mark.parametrize("protocol", PROTOCOLS)
    def test_non_slots_generated_cache_hash_reset(self, protocol):
        c = DictCacheHashTrue(12)
        h = hash(c)

        c2 = roundtrip(c, protocol)
        assert c2.__getstate__() == (12,)
        assert c2._attrs_cached_hash is None
        assert hash(c2) == h

    @pytest.mark.parametrize("protocol", PROTOCOLS)
    def test_non_slots_default_cache_hash_wrapper(self, protocol):
        c = DictCacheHashDefault(13)
        hash(c)

        c2 = roundtrip(c, protocol)
        assert c2._attrs_cached_hash is None

    def test_setstate_detection_uses_hash_defaults(self):
        from attr._make import _is_cache_hash_class

        assert _is_cache_hash_class(CacheHashBase)
        # The child gets its own non-caching frozen hash.
        assert not _is_cache_hash_class(CacheHashChild)
        # No slot for the cache on the child; setstate must not blow up.
        c2 = roundtrip(CacheHashChild(1, 2))
        assert (c2.x, c2.y) == (1, 2)

    @pytest.mark.parametrize("protocol", PROTOCOLS)
    def test_dict_child_of_cached_slots_base(self, protocol):
        obj = DictChildOfCacheHash(1, 2)
        rt = roundtrip(obj, protocol)
        assert (rt.x, rt.y) == (1, 2)
        # The stale cache from the base never travels in the tuple state.
        assert rt.__getstate__() == (1, 2)


class TestInheritance(object):
    @pytest.mark.parametrize("protocol", PROTOCOLS)
    def test_non_slots_true_parent_slots_default_child(self, protocol):
        obj = ChildSlotsDefault(1, 2)

        # No duplicated inherited field, no missing new field.
        assert obj.__getstate__() == (1, 2)
        assert BaseDictTrue(9).__getstate__() == (9,)

        rt = roundtrip(obj, protocol)
        assert (rt.a, rt.b) == (1, 2)

    @pytest.mark.parametrize("protocol", PROTOCOLS)
    def test_slots_default_parent_non_slots_true_child(self, protocol):
        obj = ChildDictTrue(3, 4)
        assert obj.__getstate__() == (3, 4)
        assert BaseSlotsDefault(9).__getstate__() == (9,)

        rt = roundtrip(obj, protocol)
        assert (rt.a, rt.b) == (3, 4)

    @pytest.mark.parametrize("protocol", PROTOCOLS)
    def test_three_levels_mixed_off_in_middle(self, protocol):
        obj = Level3(1, 2, 3)
        assert obj.__getstate__() == (1, 2, 3)

        rt = roundtrip(obj, protocol)
        assert (rt.x, rt.y, rt.z) == (1, 2, 3)

        # L2 falls back to the base slots protocol.
        rt2 = roundtrip(Level2(4, 5), protocol)
        assert (rt2.x, rt2.y) == (4, 5)

    def test_parent_and_child_both_true_no_duplication(self):
        assert BothTrueBase(1, 2).__getstate__() == (1, 2)
        assert BothTrueChild(1, 2, 3).__getstate__() == (1, 2, 3)

        rt = roundtrip(BothTrueChild(1, 2, 3))
        assert (rt.a, rt.b, rt.c) == (1, 2, 3)

    def test_multiple_base_attrs_collected_once(self):
        """
        Fields inherited across several attrs levels appear once in state.
        """
        obj = MultiBaseD(1, 2, 3, 4)
        assert obj.__getstate__() == (1, 2, 3, 4)
        rt = roundtrip(obj)
        assert (rt.a, rt.b, rt.c, rt.d) == (1, 2, 3, 4)


